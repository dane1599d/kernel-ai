//! The `models` role's targets (ADR 0008 §6; P4 task 10): each model of the
//! git-pinned catalog, `xtask/models.json`, as `<id>.gguf` with its length,
//! SHA-256 and `custom.kai` fields `name`, `licence` and `source`, the Hugging
//! Face URL at the pinned revision. The repository holds no weights: the user
//! downloads the GGUF and attaches it, and `kaipkg::models` is what the OS
//! checks it against.
//!
//! An image's repository also signs [`fixture`], the file the `app-models`
//! case attaches: every image xtask builds is signed by a throwaway test root
//! (P4 plan §4, item 3), and the release's role is signed apart from xtask
//! (task 18), so the fixture is never in it.

use crate::disk::Fixture;
use crate::models::catalog::Catalog;
use serde_json::{Value, json};

/// One target of the role.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Model {
    pub id: String,
    pub name: String,
    pub length: u64,
    /// 64 lower-case hex digits.
    pub sha256: String,
    pub licence: String,
    pub source: String,
}

impl Model {
    /// Its TUF target path, `<id>.gguf`.
    pub fn target(&self) -> String {
        format!("{}{}", self.id, kaipkg::models::EXTENSION)
    }

    /// Its `custom.kai` fields.
    pub fn index(&self) -> Value {
        json!({ "name": self.name, "licence": self.licence, "source": self.source })
    }
}

/// Every model of the catalog compiled into xtask.
pub fn catalog() -> Result<Vec<Model>, String> {
    let catalog = Catalog::load()?;
    let models = catalog.models.iter().map(|entry| Model {
        id: entry.id.clone(),
        name: entry.name.clone(),
        length: entry.size,
        sha256: entry.sha256.clone(),
        licence: entry.license.clone(),
        source: entry.url(),
    });
    Ok(models.collect())
}

/// The id [`fixture`] has.
pub const FIXTURE: &str = "fixture";

/// The `Gguf` fixture disk (`disk::Fixture::Gguf`), for test images only: the
/// GGUF magic and filler, which nothing runs. Its bytes are xtask's own, so it
/// takes a licence the import accepts.
pub fn fixture() -> Model {
    let bytes = Fixture::Gguf.bytes();
    Model {
        id: FIXTURE.into(),
        name: "Fixture model (test images only)".into(),
        length: bytes.len() as u64,
        sha256: crate::sha256_hex(&bytes),
        licence: "MIT".into(),
        source: "generated by cargo xtask: disk::Fixture::Gguf".into(),
    }
}

/// What an image's repository signs: the catalog, then [`fixture`].
pub fn for_image() -> Result<Vec<Model>, String> {
    let mut models = catalog()?;
    models.push(fixture());
    Ok(models)
}
