//! The `models` role's targets (ADR 0008 §6; P4 task 10): each model of the
//! git-pinned catalog, `xtask/models.json`, as `<id>.gguf` with its length,
//! SHA-256 and `custom.kai` fields `name`, `licence` and `source`, the Hugging
//! Face URL at the pinned revision. The repository holds no weights: the user
//! downloads the GGUF and attaches it, and `kaipkg::models` is what the OS
//! checks it against. Beside each model the role signs its `kai-chunks 1` list,
//! `<sha256>.chunks` (P5 task 6), which a download in the OS checks each chunk
//! against: a fixture's is made from its bytes, a catalog model's is committed
//! in [`super::chunks::DIR`] and held to the pin here.
//!
//! An image's repository also signs [`fixture`] and [`fixture_2`], the files
//! the `model-import` and `app-models` cases store and attach: every image
//! xtask builds is signed by a throwaway test root (P4 plan §4, item 3), and
//! the release's role is signed apart from xtask (task 18), so no fixture is
//! ever in it.

use super::chunks;
use crate::disk::Fixture;
use crate::models::catalog::Catalog;
use kainet::chunks::{CHUNK, Chunks};
use serde_json::{Value, json};

/// One target of the role.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Model {
    pub id: String,
    pub name: String,
    pub length: u64,
    /// 64 lower-case hex digits.
    pub sha256: String,
    pub licence: String,
    pub source: String,
    /// Its `kai-chunks 1` list in 2 MiB chunks, signed beside it; `None` for a
    /// catalog model whose list is not committed yet.
    pub chunks: Option<String>,
}

impl Model {
    /// Its TUF target path, `<id>.gguf`.
    pub fn target(&self) -> String {
        format!("{}{}", self.id, kaipkg::models::EXTENSION)
    }

    /// Its `custom.kai` fields.
    pub fn index(&self) -> Value {
        json!({ "name": self.name, "licence": self.licence, "source": self.source })
    }
}

/// Every model of the catalog compiled into xtask, each with its committed
/// chunk list, which must name the pinned length and SHA-256.
pub fn catalog() -> Result<Vec<Model>, String> {
    let catalog = Catalog::load()?;
    let root = crate::workspace_root();
    let models = catalog.models.iter().map(|entry| {
        let path = chunks::committed(&root, &entry.sha256);
        let list = match std::fs::read_to_string(&path) {
            Ok(text) => {
                chunks::check(&text, entry.size, &entry.sha256)
                    .map_err(|why| format!("{}: {why}", path.display()))?;
                Some(text)
            }
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
            Err(e) => return Err(format!("cannot read {}: {e}", path.display())),
        };
        Ok(Model {
            id: entry.id.clone(),
            name: entry.name.clone(),
            length: entry.size,
            sha256: entry.sha256.clone(),
            licence: entry.license.clone(),
            source: entry.url(),
            chunks: list,
        })
    });
    models.collect()
}

/// The id [`fixture`] has.
pub const FIXTURE: &str = "fixture";
/// The id [`fixture_2`] has.
pub const FIXTURE_2: &str = "fixture-2";

/// The `Gguf` fixture disk (`disk::Fixture::Gguf`), for test images only: the
/// GGUF magic and filler, which nothing runs. Its bytes are xtask's own, so it
/// takes a licence the import accepts.
pub fn fixture() -> Model {
    signed(Fixture::Gguf, FIXTURE, "Fixture model (test images only)")
}

/// The `Gguf2` fixture disk, as [`fixture`]: a second model to switch to.
pub fn fixture_2() -> Model {
    signed(
        Fixture::Gguf2,
        FIXTURE_2,
        "Second fixture model (test images only)",
    )
}

fn signed(disk: Fixture, id: &str, name: &str) -> Model {
    let bytes = disk.bytes();
    Model {
        id: id.into(),
        name: name.into(),
        length: bytes.len() as u64,
        sha256: crate::sha256_hex(&bytes),
        licence: "MIT".into(),
        source: format!("generated by cargo xtask: disk::Fixture::{disk:?}"),
        chunks: Some(Chunks::of(&bytes, CHUNK).render()),
    }
}

/// The model the release-boot case imports: the catalog's smallest.
pub const RELEASE_TEST: &str = "qwen3-0.6b";

/// What `release-image --test-root`'s repository signs: [`RELEASE_TEST`] alone.
pub fn release_test() -> Result<Vec<Model>, String> {
    let models: Vec<Model> = catalog()?
        .into_iter()
        .filter(|model| model.id == RELEASE_TEST)
        .collect();
    match models.len() {
        1 => Ok(models),
        _ => Err(format!("the catalog has no {RELEASE_TEST}")),
    }
}

/// What an image's repository signs: the catalog, then [`fixture`] and
/// [`fixture_2`].
pub fn for_image() -> Result<Vec<Model>, String> {
    let mut models = catalog()?;
    models.extend([fixture(), fixture_2()]);
    Ok(models)
}
